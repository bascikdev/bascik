/**
 * Write the catalog (the components the model may write) into
 * src/lib/catalog.generated.ts, read under Node from the component files.
 * A Worker has no component folder at runtime, so the chat imports this
 * file instead of calling `readCatalog`. The file is git-ignored: `build`,
 * `typecheck` and `unit` write it first.
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { describeComponent, readCatalog, type CatalogEntry } from "@bascik/ai";

const here = import.meta.dirname;
const ai = join(here, "..", "..", "..");
const out = join(here, "..", "src", "lib", "catalog.generated.ts");

/** The package's starter catalog, and the bookshop's card from the demo. */
export async function catalogEntries(): Promise<CatalogEntry[]> {
  const starter = await readCatalog(join(ai, "components", "catalog"));
  const cardFile = join(ai, "demo", "src", "genui", "book-card.html");
  const card = describeComponent(cardFile, await readFile(cardFile, "utf8"));
  if (!card) throw new Error(`${cardFile} is not a component.`);
  return [...starter.values(), card].sort((a, b) =>
    a.name.localeCompare(b.name),
  );
}

export function catalogSource(entries: CatalogEntry[]): string {
  return [
    "// Generated by scripts/gen-catalog.ts from ai/components/catalog and the",
    "// demo's book-card. Do not edit: run `yarn workspace bascik-ai-cloudflare catalog`.",
    'import type { CatalogEntry } from "@bascik/ai";',
    "",
    `export const CATALOG_ENTRIES: CatalogEntry[] = ${JSON.stringify(entries, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  await writeFile(out, catalogSource(await catalogEntries()));
  console.log(`Wrote ${out}.`);
}
